#!/usr/bin/env python3
"""Bundles the manufacturer index JSON into .js files so the index also works when opened from disk.

Sources (edit these, not the bundles):
  reference/csi/manifest.json and the division files it lists
  reference/research/leads.json

Outputs (generated, do not edit by hand):
  reference/csi/divisions.js   -> window.CSI_DIVISIONS
  reference/research/leads.js  -> window.RESEARCH_LEADS

Run after any change:  python3 tools/build_reference.py
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent.parent
CSI = ROOT / "reference" / "csi"
RESEARCH = ROOT / "reference" / "research"


def build():
    manifest = json.loads((CSI / "manifest.json").read_text(encoding="utf-8"))
    divisions = [json.loads((CSI / f).read_text(encoding="utf-8")) for f in manifest["files"]]
    divisions.sort(key=lambda d: d["division"])
    (CSI / "divisions.js").write_text(
        "// Generated by tools/build_reference.py from reference/csi/*.json. Do not edit by hand.\n"
        "window.CSI_DIVISIONS = " + json.dumps(divisions, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    leads = json.loads((RESEARCH / "leads.json").read_text(encoding="utf-8"))
    (RESEARCH / "leads.js").write_text(
        "// Generated by tools/build_reference.py from reference/research/leads.json. Do not edit by hand.\n"
        "window.RESEARCH_LEADS = " + json.dumps(leads, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    entries = sum(len(d["entries"]) for d in divisions)
    print(f"Bundled {len(divisions)} divisions ({entries} entries) and {len(leads['entries'])} leads")


if __name__ == "__main__":
    build()
