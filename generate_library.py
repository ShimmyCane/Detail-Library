#!/usr/bin/env python3
"""Builds library-data.js from the files under images/raw/.

Run it after adding, moving or removing files:

    python3 generate_library.py

library.html reads library-data.js. There is no database: the GitHub files are the library.
Each folder under images/raw/ is a category, and a file's folders become its tags.
"""
from pathlib import Path
import json

BASE_DIR = Path(__file__).resolve().parent
RAW_DIR = BASE_DIR / "images" / "raw"
OUT_FILE = BASE_DIR / "library-data.js"

# Raster images are shown as pictures. Vector files (SVG) and PDFs are kept at full quality.
KINDS = {
    ".png": "raster",
    ".jpg": "raster",
    ".jpeg": "raster",
    ".webp": "raster",
    ".gif": "raster",
    ".svg": "vector",
    ".pdf": "pdf",
}


def build_entries():
    if not RAW_DIR.exists():
        return []
    entries = []
    for path in sorted(RAW_DIR.rglob("*"), key=lambda p: p.as_posix().lower()):
        if not path.is_file() or path.name.startswith("."):
            continue
        kind = KINDS.get(path.suffix.lower())
        if kind is None:
            continue
        folders = list(path.relative_to(RAW_DIR).parts[:-1])
        rel = path.relative_to(BASE_DIR).as_posix()  # e.g. images/raw/roof/flashing/detail.svg
        entries.append({
            "id": rel,
            "path": rel,
            "title": path.stem,
            "kind": kind,
            "ext": path.suffix.lower().lstrip("."),
            "folder": "/".join(folders),  # "" for files directly in images/raw/
            "tags": folders,
        })
    return entries


def main():
    entries = build_entries()
    body = json.dumps(entries, indent=2, ensure_ascii=False)
    OUT_FILE.write_text(
        "// Generated by generate_library.py. Do not edit by hand.\n"
        f"window.LIBRARY_ITEMS = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(entries)} items to {OUT_FILE.name}")


if __name__ == "__main__":
    main()
